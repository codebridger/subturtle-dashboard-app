// Generates lib/src/coach/live_practice_spec.g.dart from the shared coach spec,
// shared/live-practice/spec.json at the repository root (the web imports the
// same file). Run from packages/subturtle_api after changing the spec:
//
//   dart run tool/gen_live_practice.dart
//
// The web Vitest test (frontend/tests/unit/utils/liveCoachSpec.test.ts) and the
// Dart test (test/live_practice_spec_test.dart) fail while the copy is stale.
import 'dart:convert';
import 'dart:io';

const specPath = '../../../shared/live-practice/spec.json';
const outPath = 'lib/src/coach/live_practice_spec.g.dart';

/// The generated file for [json] (the spec file's text).
String generate(String json) {
  jsonDecode(json); // must be valid JSON
  if (json.contains("'''")) throw const FormatException("The spec must not contain ''' (it is embedded in a Dart raw string).");
  return '// GENERATED by tool/gen_live_practice.dart from shared/live-practice/spec.json.\n'
      '// Do not edit by hand: change the spec, then run `dart run tool/gen_live_practice.dart`.\n'
      '\n'
      "part of 'live_practice_spec.dart';\n"
      '\n'
      "const String _specJson = r'''\n$json''';\n";
}

void main() {
  final json = File(specPath).readAsStringSync();
  File(outPath).writeAsStringSync(generate(json));
  stdout.writeln('Wrote $outPath');
}
