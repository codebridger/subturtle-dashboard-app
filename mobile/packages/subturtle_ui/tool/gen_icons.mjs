// Generates lib/src/icons/st_icon_data.g.dart from Iconify icon data.
//
// Usage (from packages/subturtle_ui):
//   node tool/gen_icons.mjs <iconify-icons.js from the design handoff> tool/extra_icons.js
//
// Sources it understands:
//   - ../../../ui/src/icon/icons.generated.ts (always read; the web kit's icon set)
//   - any file that calls addCollection({prefix, icons, width?, height?}) (the design handoff)
// Only `solar:` and `logos:` icons are kept. Later sources do not override earlier ones.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const out = new Map();

function add(name, body, width, height) {
  if (!/^(solar|logos):/.test(name) || out.has(name)) return;
  out.set(name, { body, width: width ?? 24, height: height ?? 24 });
}

// 1) The web kit's generated map: "name": { body: "...", width: N, height: N }
const webKit = path.resolve(here, '../../../../ui/src/icon/icons.generated.ts');
if (fs.existsSync(webKit)) {
  const src = fs.readFileSync(webKit, 'utf8');
  const re = /"([a-z0-9-]+:[a-z0-9-]+)":\s*\{\s*body:\s*("(?:[^"\\]|\\.)*"),\s*width:\s*(\d+),\s*height:\s*(\d+)\s*\}/g;
  for (const m of src.matchAll(re)) add(m[1], JSON.parse(m[2]), +m[3], +m[4]);
}

// 2) addCollection({...}) calls (Iconify JSON collections).
for (const file of process.argv.slice(2)) {
  const src = fs.readFileSync(file, 'utf8');
  let i = 0;
  while ((i = src.indexOf('addCollection(', i)) >= 0) {
    i += 'addCollection('.length;
    // Walk to the matching brace of the JSON object.
    let depth = 0, j = i, inStr = false;
    for (; j < src.length; j++) {
      const c = src[j];
      if (inStr) { if (c === '\\') j++; else if (c === '"') inStr = false; continue; }
      if (c === '"') inStr = true;
      else if (c === '{') depth++;
      else if (c === '}') { depth--; if (depth === 0) { j++; break; } }
    }
    const col = JSON.parse(src.slice(i, j));
    for (const [n, def] of Object.entries(col.icons)) {
      add(`${col.prefix}:${n}`, def.body, def.width ?? col.width, def.height ?? col.height);
    }
    i = j;
  }
}

const names = [...out.keys()].sort();
const dartString = (s) => "r'''" + s.replace(/'''/g, "' ''") + "'''";
let dart = `// GENERATED by tool/gen_icons.mjs. Do not edit by hand.\n// Source: Iconify Solar + Logos icon data (MIT / CC0), the same set the web kit uses.\n\npart of 'st_icon.dart';\n\nconst Map<String, StIconData> _stIconData = {\n`;
for (const n of names) {
  const d = out.get(n);
  dart += `  '${n}': StIconData(${dartString(d.body)}, ${d.width}, ${d.height}),\n`;
}
dart += '};\n';
const target = path.resolve(here, '../lib/src/icons/st_icon_data.g.dart');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, dart);
console.log(`Wrote ${names.length} icons to ${path.relative(process.cwd(), target)}`);
